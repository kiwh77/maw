//
// 这个包只做判定，不做实现：
//   - 受管执行（managed）目前只有 macOS 有原生证据，其它平台必须保持「不支持」，
//     不能因为能编译就顺手把能力打开；
//   - 跨编译与原生进程实测是两件事，跨编译通过只说明代码能编，不说明能起进程；
//   - 桌面壳与前端产物的构建前置条件（Cargo／capabilities／vite／已嵌入的 bundle）
//     要在 CI 里能被单独检查，否则发布当天才发现缺件。
//
// 这里的所有断言都以 `runtime.GOOS` 为参照，因此同一份用例在任何平台跑都成立：
// 在 macOS 上验证「支持」，在其它平台上验证「拒绝」，而不是写死某一端。
