// Package nongit 准备非 Git 项目的受管任务目录。
//
// 独立文档与调研任务没有仓库可切分支，但「这个目录现在归谁」是同一个问题：
// 上一份结果还没验收就复用目录，等于把唯一一份产物冲掉。所以本包与 Git 工作空间
// （internal/workspace）共享同一个占用判定（workspace.Index／Occupant），
// 只在目录形态上不同：
//
//   - 产物根由调用方显式给出（Request.Root），不做向上搜索。非 Git 没有「仓库根」
//     这个概念，从子目录猜出来的根会把产物放到错的位置，而且猜错的代价是覆盖别人的文件。
//   - 默认任务目录是 <产物根>/.maw-work/<agent>（架构 §10.4 的文件布局），
//     同一 Agent 复用同一目录，目录数量不随任务数增长。
//   - 显式 Path 必须落在本工程产物根之下。跨工程路径一律拒绝：两个工程写进同一份
//     产物目录，之后谁都不敢清理，也分不清哪份结果属于哪道题。
//   - 仓库内的文档不走这里。产物根或任务目录只要落在任何 Git 工作树里就拒绝，
//     并指回 internal/workspace——那边有基线提交与任务分支可回溯，能冻结、能回滚。
//
// 三条硬规则：
//
//   - 占用检查发生在任何 mkdir 之前。运行仍计入占用（阶段非终态、核实状态 unknown、
//     failed/cancelled 但进程未确认停止）或产物未冻结时不得复用目录，返回 E240。
//     判断复用 model.Run.Occupies()，本包不另写一套阶段规则。
//   - 复用不清理、不重置、不覆盖：本包从不删除目录内容，复用的语义是「原地继续」，
//     已有产物按字节保留，只在结果里列出保住了哪些条目。清理是验收之后的事。
//   - 失败不改现场：不建目录、不回滚、不删东西，把只读现场（Before/After）一起返回，
//     人工据此判断是「谁挡住」还是「名字被占」。
//
// 与 Git 版的差别只在校验对象：这里没有分支、没有基线提交、没有 HEAD，
// 于是 Freeze/Prepare 校验换成「产物根仍在且仍不是 Git」「任务目录仍是目录且在根下」。
//
// 本包不做结果验收（VN-505 负责），也不改 Git 实现。
