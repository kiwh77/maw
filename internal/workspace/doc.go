// Package workspace 准备受占用保护的 Git 工作空间。
//
// 它把「要不要动这个目录」和「怎么动」分成两步：Freeze 只读地冻结目录、分支与
// 基线提交；Prepare 先做规范化路径的独占检查，再调 internal/gitops 的既有操作。
// 顺序是硬要求——占用检查必须发生在任何 reset／checkout 之前，否则等于用别人的
// 未验收产物换一张新工位。
//
// 三条规则来自 maw.runtime.state/v1 §4／§4.1，本包只做判定，不发明新语义：
//
//   - 运行仍在占用（阶段非终态、核实状态 unknown、failed/cancelled 但进程未确认
//     停止）的目录不得复用；产物未冻结的同样算占用（E242 的另一面）。
//   - 目录键是清理后的绝对路径；同一目录的别名（尾斜杠、./、..、符号链接）必须
//     收敛成一个键，否则独占检查会被绕过去。
//   - 准备失败不改现场：不清理、不回滚、不删除。失败结果带只读采集的现场，
//     人工据此核对是「谁挡住」还是「目录已脏」。
//
// 两条容易踩的边界：
//
//   - 目录必须「本身」是工作树根。工程里的普通子目录跑 rev-parse --show-toplevel
//     会解析到工程根，把它当工作树 reset 会把主干工作区一起重置。判据是
//     「解析结果就是自己」，不是「能解析出仓库」。
//   - 已跟踪文件有未提交改动时默认拒绝复用，因为 reset --hard 丢掉的改动找不回来；
//     调用方显式传 Options.AllowDiscard 才继续，并在结果里列出丢掉了哪些。
//
// 本包不修改 internal/gitops 的既有规则，也不操作真实仓库：所有写操作都经由
// gitops.EnsureAgentWorktree／gitops.CreateWorktree，测试用临时仓库验证边界。
