// Package query 提供一致快照上的权威查询与游标分页。
//
// 它只读：所有查询都跑在一个 deferred 只读事务里（internal/db 的 Store.Read），
// 不使用写事务、不加写锁、不执行 DDL。一次 Read 内的多个查询看到的是同一份快照，
// 并共享同一个水位（Watermark）——列表返回的 revision／cursor 因此能说明「这是哪一刻」。
//
// 三条规则直接来自 HTTP 契约 §2：
//
//   - 游标分页，拒绝 offset／page；limit 省略为 50，允许 1–200，越界报错而不是静默截断。
//   - 排序稳定且与游标一致；游标是不透明字符串，客户端只能原样回传。
//   - 翻页期间数据变化不回退游标：游标记的是「上一页最后一条的排序键」，
//     而不是偏移量，所以并发插入不会让后面的记录被跳过或重复。
//
// 两处最容易出错的地方，本包用测试钉住：
//
//   - 过滤必须下推到 SQL，而不是先取一页再在内存里筛。否则筛空的页会带着
//     next_cursor 返回，客户端读到一个空页就停下，后面的匹配记录永远看不到。
//   - 排序键不唯一时必须补足到唯一（同名历史：同一 display_id 有多个实例）。
//     只按 name 做 `> last` 的游标会跳过所有同名记录。
//
// 本包不实现 HTTP 映射与统计聚合：错误只给契约里的 error.code，
// 由接入层决定状态码（invalid_pagination／unknown_enum → 422）。
