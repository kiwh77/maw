// Package localauth 实现本机控制接口的凭据生命周期与同源防护：
// CLI 令牌（Bearer）与浏览器会话（Cookie + CSRF），依据 docs/contracts/vnext/http/ 的 §7。
//
// 三条边界（对应契约 §7.5「不承诺强隔离」）：
//
//  1. 本包只保证「浏览器跨站请求不能借会话改状态」与「没有有效令牌的远端进程不能调用」。
//  2. **不**承诺同一操作系统用户下进程之间的隔离：同用户可以读令牌文件、连同一个
//     loopback 端口、伪造 Host/Origin。需要强隔离请换独立系统用户、独立数据目录或容器。
//  3. 令牌只走 `Authorization: Bearer`，禁止 query／body 传递；本包的任何响应、错误体
//     与日志辅助函数都不会回显明文令牌，回显即视为泄漏。
//
// 本包不接线到现有路由（VN-601 的 non-goal），只提供可测的凭据、会话与中间件；
// 路由挂载与资源实现属于后续 HTTP 卡。
