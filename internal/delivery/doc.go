// Package delivery 把一次运行的候选结果冻成可长期引用的交付快照。
//
// 职责边界（本卡 VN-502）：
//
//   - 核实 CLI 声明的产物：实体在不在、有没有越出本卡写盘范围、内容哈希是多少。
//     「CLI 说它产出了」只是候选，不是事实（契约 §3）。
//   - 核实提交链：候选提交必须是仓库里真实存在的对象，基线必须是它的祖先，
//     两者之间的改动必须全部落在 write_scope 内。
//   - 冻结：把核实过的事实连同验证／评审／合入结论一起写成 model.Delivery，
//     并按契约 §5 推导完成判定——推不出来就只能是 pending，绝不「大概完成」。
//   - 幂等：同一份候选重复收取必须得到同一个 delivery_id 与同一份快照，
//     不产生第二次交付。
//
// 不做的事：不执行验证命令、不做评审、不执行合入（VN-503 及之后）。
//
// # 为什么引用提交而不是引用目录
//
// 工作目录会被下一道题 reset 掉，路径本身不是证据。所以：
//
//   - 提交类产物以 git 对象是否存在为准（对象存在，目录怎么复用都不影响）；
//   - 文件类产物优先从候选提交里取内容（`git cat-file`），只有提交里没有、
//     磁盘上才有时才读磁盘，且这种产物**不能支撑 done**——它在目录复用后就没了。
//
// 这条规则就是验收里「目录复用后仍有效」与「缺失结果不被标记为通过」的落点。
//
// # 返回值的语义
//
// Collect／Freeze 返回的交付**总是可用**：即使错误非空，里面也是「本次冻结的全部事实 +
// pending 判定」。错误的含义是「这份交付里有硬问题（越界、产物查不到、验证过期）」，
// 不是「冻结失败」。这两件事必须分开看：判不出 done 是正常结论，事实不干净才是问题。
