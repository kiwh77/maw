// Package reconcile 给出「证据不足时怎么办」的恢复决策：心跳失联进入核实、
// 取消与结束事实竞争、显式停止、任务取消、重试与会话恢复的资格判定。
//
// 契约来源：
//
//	docs/contracts/vnext/execution/runtime-state-contract-v1.md §3–§6
//	docs/ARCHITECTURE_VNEXT.zh-CN.md §8（RunSpec、停止证据与恢复）
//
// 三条边界：
//
//  1. **不做存储调用、不启停进程**。本包只依据调用方传入的运行状态与进程观测
//     回答「下一步能做什么」，落库、发信号、建 worktree 都由上层完成。
//  2. **不猜测**。心跳丢失不是停止证据，结果未判定不补造结果；无法确认后代
//     停止时保留占用并标注待核实。来源会话缺失时不得发起恢复。
//  3. **人工证据保留来源**。人工确认必须记录引用与处理人，才能顶替自动观测；
//     它同样只回答事实，不替代运行结果判定。
