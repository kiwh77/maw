// 三条边界：
//
//  1. **自动模式默认关闭。** 零值 Policy 不会自动选题；开启自动执行必须同时给出
//     正整数受管执行上限，否则按 E270 拒绝。人工领取走 PickManual，只看任务队列
//     规则，不读自动执行开关与受管上限——自动配额不能偷换人工 next 的语义。
//  2. **选择顺序固定。** 任务按 priority→merge_order→id；节点按工程策略的偏好序，
//     再按 node_id。输入顺序不影响结果，同等候选重复调用结果一致。
//  3. **纯函数、不做副作用。** 不探测进程、不读数据库、不写任务状态；调用方把
//     db／nodes 的只读投影填进来，真正的占用仍由 ClaimExecution 事务完成。
//
