// Package session 把「来源进程、语义日志、持久操作」串成一次 Run 的生命周期。
//
// 一次 Run 的固定顺序：
//
//	提交 running 事实 → 启动进程 → 逐行摄取 → 结束判定 → 提交终态事实
//
// 三条边界（本卡验收就落在这三条上）：
//
//   - **事实只走应用端口**：启动、阶段变更、来源事件、终态都通过 Store 端口提交；
//     本包不碰数据库、不写任务状态、不释放占用。没有 lease_release、没有 task_status，
//     连一行这样的代码都不该出现——「心跳不直接释放业务任务」是结构保证，不是纪律要求。
//   - **输出先落盘再提交**：每一行来源记录先 append 进 journal（本机持久），再尝试提交。
//     中枢掉线时提交失败不致命，记录留在 pending；心跳把 pending 补交上去。
//     于是「中枢掉线 → 恢复 → 补交」不需要任何特殊分支。
//   - **协议结果不绕过验收**：Interpret 给出的 completed 只对应 run.phase=completed，
//     它不会把任务标成 done；unknown 连终态都不落（E232），只留待核实。
//
// # 与 internal/runner/process 的关系
//
// process 包管的是进程身份、进程组停止与锁；它不捕获输出（StartSpec 没有 stdout 管道）。
// 本包需要逐行读输出，所以执行走本包自己的 starter 抽象，默认实现是 os/exec +
// 便携信号（Interrupt → Kill）。要换成按进程组确认停止，注入别的 starter 即可，
// 摄取、提交、幂等这些语义不受影响。
//
// # 三个踩过的坑（改这条链路前先看）
//
//  1. **不要用 cmd.StdoutPipe() 配并发 Wait**：Wait 会关闭读端，还没读完的行会被截断，
//     表现为「有时 3 行、有时 1 行」。本包自建 os.Pipe（父进程只留读端），
//     并把 cmd.Wait() 收进唯一的 collect 协程。
//  2. **只留一条交付通道**：摄取、心跳、收尾都调 deliver（内部串行 + 走 journal.Resubmit）。
//     各自提交会让同一条记录被提交两次，时间轴上凭空多出事件。
//  3. **游标由 Resubmit 按序推进**，别自己按 seq 跳着 checkpoint——那会跳过中间还
//     没交的记录，等于把待补交的事实悄悄丢掉。
