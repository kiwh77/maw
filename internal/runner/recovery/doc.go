// Package recovery 在监督进程重启后，重新确认一次 Run 的现场。
//
// 它回答四个互斥的问题（本卡验收第一条）：
//
//	running      进程确实还在跑（监督关系丢了，进程没丢）
//	finished     进程确定结束，且进程组已清空
//	not_started  从来没启动过（没有身份记录，日志也没有记录）
//	unknown      证据不足（进程组还有存活成员、身份记录损坏、日志有记录但身份丢了）
//
// 以及第二个问题：这块现场能不能被下一道题复用。
//
// # 两条硬规则
//
//   - **证据不足一律保留现场**：unknown 与 running 都保持资源占用、都禁止换目录重跑。
//     重跑同题会把「可能还在跑的进程」和「新进程」写进同一个任务实例，
//     时间轴上会出现两个占用，而其中一个根本没人管。
//   - **只读**：本包不发信号、不清理进程、不改身份记录。要停止走 ProcessController，
//     要补交走 session.Recover；这里只给结论和证据。
//
// # 与 internal/runner/process 的关系
//
// 进程身份的核对完全交给 process.Recover：它按 PID + 启动时间识别 PID 复用，
// 按进程组确认后代是否清空。本包不自己读 /proc 或 ps，也不「大概判断」。
